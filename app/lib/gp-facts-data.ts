/** Researched 27 October 2026. Append facts; existing numbered IDs are retained across releases. */
export type FactSource = { title: string; url: string };
export type GrandPrixFact = { id: string; text: string; source: FactSource };
export type FactPack = {
  key: string;
  name: string;
  circuits: string[];
  races: string[];
  facts: GrandPrixFact[];
};
type Input = string | { text: string; source: FactSource };
const source = (url: string, title = "Formula 1") => ({ title, url });
const extra = (text: string, url: string, title = "Formula 1"): Input => ({
  text,
  source: source(url, title),
});
const profile = (slug: string, year = 2025) =>
  source(`https://www.formula1.com/en/racing/${year}/${slug}`);
function pack(
  key: string,
  name: string,
  circuits: string[],
  races: string[],
  reference: FactSource,
  texts: Input[],
): FactPack {
  return {
    key,
    name,
    circuits,
    races,
    facts: texts.map((input, i) => ({
      id: `${key}-${i + 1}`,
      text: typeof input === "string" ? input : input.text,
      source: typeof input === "string" ? reference : input.source,
    })),
  };
}

